/**
 * 会出现在「经 …」、作者、命令行和日志里的名字（令牌的名称、用户的显示名、写操作的昵称）里不能有的字符。
 *
 * **目标只有一个：名字不能在控制台和终端里倒着显示、藏字、换行。** 不承诺「看起来一模一样的名字不能同时有效」：
 * 同一个字的预组合和分解写法、西里尔字母冒充拉丁字母、韩文填充符这类看不见但不是格式字符的字符，都不在这里拦（要拦得做规范化、
 * 唯一约束、处理已有的数据，不是这个检查的事）。
 *
 * **拒绝的是下面这张明确的表，不是某个 Unicode 类别**：
 * - C0 控制字符（U+0000–U+001F：NUL、制表、换行、回车、转义序列 ESC……）、DEL（U+007F）、C1 控制字符（U+0080–U+009F）：
 *   会把终端和日志弄乱；
 * - 行分隔符、段分隔符（U+2028、U+2029）：换行；
 * - 双向文字的控制字符：嵌入和覆盖（U+202A–U+202E）、隔离（U+2066–U+2069）、方向标记（U+200E、U+200F、U+061C）：
 *   让名字倒着显示、让别的字看起来在名字里面（藏字）；
 * - 纯粹看不见、没有正当用途的字符：零宽空格（U+200B）、词连接符（U+2060）、字节顺序标记（U+FEFF）、软连字符（U+00AD）。
 *
 * **放行**：零宽连接符（U+200D）、零宽不连字符（U+200C）、变体选择符（U+FE00–U+FE0F、U+E0100–U+E01EF）、标签字符
 * （U+E0020–U+E007F）。正常的文字和表情要用它们：波斯文、僧伽罗文、印地文，带零宽连接符的组合表情（👩‍💻），子区域旗（英格兰、苏格兰）。
 */
// `\p{Cc}` 就是 C0（U+0000–U+001F）、DEL（U+007F）和 C1（U+0080–U+009F），正好是上面表里的前三项，不多不少。
export const UNSAFE_NAME_CHARACTER =
	/[\p{Cc}\u00AD\u061C\u200B\u200E\u200F\u2028\u2029\u202A-\u202E\u2060\u2066-\u2069\uFEFF]/u;

/** 名字里有没有上面那张表里的字符。 */
export const hasUnsafeNameCharacter = (text: string): boolean => UNSAFE_NAME_CHARACTER.test(text);

/** 名字里有表里的字符时给调用方看的说明（令牌的名称、显示名、昵称共用）；`what` 是「令牌的名称」「显示名」「昵称」。 */
export const unsafeNameMessage = (what: string): string =>
	`${what}里不能有控制字符（换行、转义序列等）、双向文字的控制字符和零宽空格这类看不见的字符`;
