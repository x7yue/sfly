#!/usr/bin/env bash
# 把宿主工作区里要同步的文件复制进卷里的副本（entry.sh 调用，#589）。
#
# 用法：sync-copy.sh <源目录> <清单文件（NUL 分隔）> <目标目录>
#
# 复制的规则是「内容变了的文件，修改时间变成现在」，不是「修改时间跟着宿主走」：
# - `rsync -a` 会把修改时间也还原成宿主上的：卷里的文件被改过（在容器里做变异）、或者宿主上换了一份内容而它的修改时间
#   比卷里的更早时，同步换回了内容，修改时间却变得更早；cargo 按修改时间判断要不要重编，看到源文件比已有的编译结果还早，
#   就接着用旧的二进制，测试跑的不是眼前这份源码，而且没有任何提示。
# - `--no-times` 让 rsync 不再还原修改时间：写过的文件，修改时间就是写它的这一刻，比卷里已有的编译结果新，cargo 会重编；
# - `--checksum` 按内容判断要不要写：内容没变的文件一律不动、修改时间不变（没有它，不还原修改时间之后每个文件的修改时间
#   都和宿主不同，每次同步都会重写全部文件，cargo 每次都整个重编）。要同步的是 `git ls-files` 列出的源文件，
#   多读一遍内容只要零点几秒。
# 删掉宿主上已经不存在的文件不在这里（entry.sh 按上次的清单删）。
set -euo pipefail

src=${1:?用法：sync-copy.sh <源目录> <清单文件（NUL 分隔）> <目标目录>}
list=${2:?用法：sync-copy.sh <源目录> <清单文件（NUL 分隔）> <目标目录>}
dest=${3:?用法：sync-copy.sh <源目录> <清单文件（NUL 分隔）> <目标目录>}

rsync -a --no-times --checksum --files-from="$list" --from0 "${src%/}/" "${dest%/}/"
